import { describe, it, expect } from 'vitest';
import { parse } from '../src/index.js';

// 기준: 2026-10-30 (금) 14:00
const ref = new Date(2026, 9, 30, 14, 0);
const d = (y: number, m: number, day: number, h = 0, min = 0) => new Date(y, m - 1, day, h, min);

// 메신저 말투 예문. 기대값은 사람이 판단해서 적는다.
// ⚠️ 지금은 Claude가 작성한 예문이다. 실제 카톡·슬랙·메일에서 본 문장으로 계속 보강할 것.
// [입력, 기대 date, 기대 end?]
const cases: [string, Date | null, Date?][] = [
  ['담주 월욜 점심 ㄱ?', d(2026, 11, 2, 12)],
  ['낼 오후 2시에 회의 있어요', d(2026, 10, 31, 14)],
  ['모레 저녁 7시 강남역 어때?', d(2026, 11, 1, 19)],
  ['다음주 수요일까지 제출해주세요', ref, d(2026, 11, 4, 23, 59)],
  ['이번 주 안에 보내주세요', ref, d(2026, 11, 1, 23, 59)],
  ['다음주 중으로 회신 부탁드립니다', ref, d(2026, 11, 8, 23, 59)],
  ['토욜 오전 11시 브런치 콜?', d(2026, 10, 31, 11)],
  ['일욜 낮 1시에 보자', d(2026, 11, 1, 13)],
  ['금욜 저녁에 한잔?', d(2026, 10, 30, 19)],
  ['11월 5일 목요일 오후 4시 미팅입니다', d(2026, 11, 5, 16)],
  ['12/24 저녁 7시 예약했어', d(2026, 12, 24, 19)],
  ['3일 뒤에 다시 연락드릴게요', d(2026, 11, 2)],
  ['일주일 뒤에 봬요', d(2026, 11, 6)],
  ['30분 뒤에 출발해', d(2026, 10, 30, 14, 30)],
  ['한 시간 반 뒤에 도착 예정', d(2026, 10, 30, 15, 30)],
  ['이번달 말까지 정산 부탁해요', ref, d(2026, 10, 31, 23, 59)],
  ['다음달 초에 이사해', d(2026, 11, 1)],
  ['다음 달 중순쯤 휴가 가려고', d(2026, 11, 15)],
  ['내년 초에 이직 생각 중', d(2027, 1, 1)],
  ['올해 말까지 끝내자', ref, d(2026, 12, 31, 23, 59)],
  ['이번 주말에 시간 돼?', d(2026, 10, 31)],
  ['주말에 영화 보러 갈래?', d(2026, 10, 31)],
  ['다음주 화요일 오후 3시 괜찮으세요?', d(2026, 11, 3, 15)],
  ['내일은 오전 10시 반까지 출근', ref, d(2026, 10, 31, 10, 30)],
  ['오늘 밤 11시에 전화할게', d(2026, 10, 30, 23)],
  ['내일 새벽 5시 비행기야', d(2026, 10, 31, 5)],
  ['내일 아침 8시 반에 깨워줘', d(2026, 10, 31, 8, 30)],
  ['2026-11-20 오후 2시 면접', d(2026, 11, 20, 14)],
  ['27년 3월 2일 입학', d(2027, 3, 2)],
  ['11월 1일부터 11월 3일까지 휴가입니다', d(2026, 11, 1), d(2026, 11, 3, 23, 59)],
  ['내일 오후 2시부터 4시까지 회의실 잡았어요', d(2026, 10, 31, 14), d(2026, 10, 31, 16)],
  ['토요일 오후 1~3시 사이에 방문 예정', d(2026, 10, 31, 13), d(2026, 10, 31, 15)],
  ['다다음주 월요일 출장', d(2026, 11, 9)],
  ['지난주 수요일에 보낸 메일 확인해주세요', d(2026, 10, 21)],
  ['어제 저녁에 얘기한 거', d(2026, 10, 29, 19)],
  ['그저께 점심 먹은 데', d(2026, 10, 28, 12)],
  ['내일모레 시간 돼?', d(2026, 11, 1)],
  ['밥 먹었어?', null],
  ['오일 교환 언제 했더라', null],
  ['평일엔 바빠', null],
];

describe('메신저 문장', () => {
  for (const [input, date, end] of cases) {
    it(input, () => {
      const r = parse(input, { referenceDate: ref });
      if (date === null) return expect(r).toBeNull();
      expect(r?.date).toEqual(date);
      if (end) expect(r?.end).toEqual(end);
    });
  }
});
